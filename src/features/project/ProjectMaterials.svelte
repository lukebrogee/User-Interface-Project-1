        <h3>Documentation</h3>
        <p>This project was built using Svelte and JavaScript to create a front-end prototype for a smart plant pot interface. The application is structured into modular sections that make the code easier to understand, update, and expand as the product evolves.</p>
        <p>The core of the project is the page layout, which brings together the overall structure, cards, and interactive components so the interface feels like a complete product prototype. Reusable feature components keep the code organized and readable, while the data layer provides realistic mock plant values for health, moisture, watering, and light conditions.</p>
        <p>AI was used to help structure the project and write clean, maintainable code. It assisted in organizing the layout, defining how the features communicate with each other, and supporting the logic behind the smart care simulation to make the prototype feel realistic and production-ready.</p>
        <p>For future work, a mobile application could allow users to monitor their plants remotely, adjust controls while away from home, and view historical trends in moisture, watering, and plant health over time.</p>
